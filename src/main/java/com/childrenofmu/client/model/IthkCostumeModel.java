package com.childrenofmu.client.model;

import java.util.ArrayList;
import java.util.EnumMap;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

import com.childrenofmu.ChildrenOfMu;
import com.childrenofmu.entity.ithk.IthkProfession;
import com.mojang.blaze3d.vertex.PoseStack;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeDeformation;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.client.renderer.LightTexture;
import net.minecraft.client.renderer.MultiBufferSource;
import net.minecraft.client.renderer.RenderType;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.util.Mth;

/**
 * The profession costumes, drawn on top of the eye. They turn left and right with the eye but don't tilt up
 * and down with it. Geometry comes from IthkCostumeShapes (generated by tools/make_ithk_costumes.py).
 */
public class IthkCostumeModel {
    public static final ModelLayerLocation LAYER =
            new ModelLayerLocation(ChildrenOfMu.id("ithk_costume"), "main");

    private static final int ETHEREAL_COLOR = 0x7040FF80;
    /** How fast the transmuter's cones spin, in radians per tick. */
    private static final float CONE_SPIN = 0.03F;

    private final ModelPart body;
    private final Map<IthkProfession, Map<IthkCostumeShapes.Layer, List<ModelPart>>> parts = new EnumMap<>(IthkProfession.class);
    private final List<ModelPart> spinning = new ArrayList<>();

    public IthkCostumeModel(ModelPart root) {
        this.body = root.getChild("body");
        for (IthkCostumeShapes.Part p : IthkCostumeShapes.PARTS) {
            ModelPart mp = this.body.getChild(p.name());
            IthkProfession prof = IthkProfession.byId(p.profession());
            this.parts.computeIfAbsent(prof, k -> new EnumMap<>(IthkCostumeShapes.Layer.class))
                    .computeIfAbsent(p.layer(), k -> new ArrayList<>())
                    .add(mp);
            if (p.name().startsWith("transmuter_")) {
                this.spinning.add(mp);
            }
        }
    }

    public static LayerDefinition createLayer() {
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition body = mesh.getRoot().addOrReplaceChild("body", CubeListBuilder.create(),
                PartPose.offset(0.0F, 16.0F, 0.0F));
        for (IthkCostumeShapes.Part p : IthkCostumeShapes.PARTS) {
            CubeListBuilder cubes = CubeListBuilder.create();
            for (IthkCostumeShapes.Box b : p.boxes()) {
                cubes.texOffs(b.u(), b.v()).addBox(b.x(), b.y(), b.z(), b.w(), b.h(), b.d(),
                        new CubeDeformation(b.growX(), b.growY(), b.growZ()));
            }
            body.addOrReplaceChild(p.name(), cubes, PartPose.offsetAndRotation(
                    p.pivotX(), p.pivotY(), p.pivotZ(),
                    p.rotX() * Mth.DEG_TO_RAD, p.rotY() * Mth.DEG_TO_RAD, p.rotZ() * Mth.DEG_TO_RAD));
        }
        return LayerDefinition.create(mesh, IthkCostumeShapes.TEX_SIZE, IthkCostumeShapes.TEX_SIZE);
    }

    private static ResourceLocation texture(String name) {
        return ChildrenOfMu.id("textures/entity/ithk/" + name + ".png");
    }

    private static final Map<IthkProfession, ResourceLocation> TEXTURES = new HashMap<>();
    private static final ResourceLocation SHEEN_TEXTURE = texture("costume_transmuter_sheen");

    private static ResourceLocation textureFor(IthkProfession prof) {
        return TEXTURES.computeIfAbsent(prof, p -> texture("costume_" + p.id()));
    }

    public void render(IthkProfession profession, PoseStack poseStack, MultiBufferSource buffers, int light, int overlay,
                       float ageInTicks, float netHeadYaw, boolean ethereal, int seed) {
        Map<IthkCostumeShapes.Layer, List<ModelPart>> layers = this.parts.get(profession);
        if (layers == null) {
            return;
        }

        this.body.yRot = netHeadYaw * Mth.DEG_TO_RAD;
        for (ModelPart mp : this.spinning) {
            mp.yRot = ageInTicks * CONE_SPIN;
        }

        poseStack.pushPose();
        this.body.translateAndRotate(poseStack);
        ResourceLocation tex = textureFor(profession);

        if (ethereal) {
            // Ghostly green, see-through and glowing, like the eye's wireframe.
            var buffer = buffers.getBuffer(RenderType.entityTranslucent(tex));
            for (List<ModelPart> list : layers.values()) {
                for (ModelPart mp : list) {
                    mp.render(poseStack, buffer, LightTexture.FULL_BRIGHT, overlay, ETHEREAL_COLOR);
                }
            }
            poseStack.popPose();
            return;
        }

        List<ModelPart> base = layers.get(IthkCostumeShapes.Layer.BASE);
        if (base != null) {
            var buffer = buffers.getBuffer(RenderType.entityCutoutNoCull(tex));
            for (ModelPart mp : base) {
                mp.render(poseStack, buffer, light, overlay, 0xFFFFFFFF);
            }
        }

        List<ModelPart> sheen = layers.get(IthkCostumeShapes.Layer.SHEEN);
        if (sheen != null) {
            // Iridescent streaks drifting through the rainbow.
            float hue = ((ageInTicks + seed * 37) * 0.004F) % 1.0F;
            int color = 0xFF000000 | (Mth.hsvToRgb(hue, 0.55F, 1.0F) & 0xFFFFFF);
            var buffer = buffers.getBuffer(RenderType.entityTranslucentEmissive(SHEEN_TEXTURE));
            for (ModelPart mp : sheen) {
                mp.render(poseStack, buffer, LightTexture.FULL_BRIGHT, overlay, color);
            }
        }

        List<ModelPart> lining = layers.get(IthkCostumeShapes.Layer.LINING);
        if (lining != null) {
            // The cape's inside: a slow, glowing shift through every color.
            float hue = ((ageInTicks + seed * 53) * 0.006F) % 1.0F;
            float pulse = 0.75F + 0.25F * Mth.sin(ageInTicks * 0.05F);
            int color = 0xFF000000 | (Mth.hsvToRgb(hue, 0.85F, pulse) & 0xFFFFFF);
            var buffer = buffers.getBuffer(RenderType.entityCutoutNoCull(tex));
            for (ModelPart mp : lining) {
                mp.render(poseStack, buffer, LightTexture.FULL_BRIGHT, overlay, color);
            }
        }

        poseStack.popPose();
    }
}
