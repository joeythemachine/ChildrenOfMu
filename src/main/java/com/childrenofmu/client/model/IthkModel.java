package com.childrenofmu.client.model;

import com.childrenofmu.ChildrenOfMu;
import com.childrenofmu.entity.ithk.IthkEntity;
import com.childrenofmu.entity.ithk.IthkEyeColors;
import com.mojang.blaze3d.vertex.PoseStack;
import com.mojang.blaze3d.vertex.VertexConsumer;
import net.minecraft.client.model.EntityModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeDeformation;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.client.renderer.LightTexture;
import net.minecraft.util.Mth;

/**
 * A 14px voxel sphere with an iris (pupil painted on) at the front. Blinking swaps the iris for a closed lid
 * of the same shape.
 * The sphere's boxes and both textures come from tools/make_ithk_assets.py: change that script and re-run it.
 */
public class IthkModel extends EntityModel<IthkEntity> {
    public static final ModelLayerLocation LAYER =
            new ModelLayerLocation(ChildrenOfMu.id("ithk"), "main");

    /** Ethereal wireframe tint: white (the texture is already green), slightly see-through. */
    private static final int ETHEREAL_COLOR = 0xE0FFFFFF;

    private final ModelPart body;
    private final ModelPart shell;
    private final ModelPart iris;
    private final ModelPart lid;

    // Per-frame state copied from the entity in setupAnim.
    private boolean ethereal;
    private boolean blinking;
    private int eyeColor = 0xFFFFFFFF;

    public IthkModel(ModelPart root) {
        this.body = root.getChild("body");
        this.shell = this.body.getChild("shell");
        this.iris = this.body.getChild("iris");
        this.lid = this.body.getChild("lid");
    }

    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();

        // Pivot at the sphere's center, 8px above the ground line (model y=24 is the ground).
        PartDefinition body = root.addOrReplaceChild("body", CubeListBuilder.create(), PartPose.offset(0.0F, 16.0F, 0.0F));

        // The voxel sphere: many small non-overlapping boxes, generated by tools/make_ithk_assets.py.
        CubeListBuilder shell = CubeListBuilder.create();
        for (int[] b : IthkShape.SHELL) {
            shell.texOffs(b[0], b[1]).addBox(b[2], b[3], b[4], b[5], b[6], b[7]);
        }
        body.addOrReplaceChild("shell", shell, PartPose.ZERO);

        // Slightly shrunk so their sides never sit exactly on the sphere's faces (which would flicker).
        CubeDeformation inset = new CubeDeformation(-0.02F);
        body.addOrReplaceChild("iris", CubeListBuilder.create()
                        .texOffs(IthkShape.IRIS_U, IthkShape.IRIS_V).addBox(-3.0F, -3.0F, -7.5F, 6, 6, 1, inset),
                PartPose.ZERO);
        // The closed eye: the same shape as the iris, drawn instead of it while blinking.
        body.addOrReplaceChild("lid", CubeListBuilder.create()
                        .texOffs(IthkShape.LID_U, IthkShape.LID_V).addBox(-3.0F, -3.0F, -7.5F, 6, 6, 1, inset),
                PartPose.ZERO);

        return LayerDefinition.create(mesh, IthkShape.TEX_WIDTH, IthkShape.TEX_HEIGHT);
    }

    @Override
    public void setupAnim(IthkEntity entity, float limbSwing, float limbSwingAmount, float ageInTicks,
                          float netHeadYaw, float headPitch) {
        // The whole body is the eye, so it turns to look at things.
        this.body.yRot = netHeadYaw * Mth.DEG_TO_RAD;
        this.body.xRot = headPitch * Mth.DEG_TO_RAD;

        this.ethereal = entity.isEthereal();
        this.blinking = entity.isBlinking();
        this.eyeColor = IthkEyeColors.COLORS[entity.getEyeColorIndex()];
    }

    @Override
    public void renderToBuffer(PoseStack poseStack, VertexConsumer buffer, int packedLight, int packedOverlay, int color) {
        // Blinking swaps the iris for the closed lid. Same shape, so nothing pops out.
        this.lid.visible = this.blinking;
        this.iris.visible = !this.blinking;

        poseStack.pushPose();
        this.body.translateAndRotate(poseStack);

        if (this.ethereal) {
            // Glowing green wireframe, full brightness regardless of surroundings.
            int light = LightTexture.FULL_BRIGHT;
            this.shell.render(poseStack, buffer, light, packedOverlay, ETHEREAL_COLOR);
            this.iris.render(poseStack, buffer, light, packedOverlay, ETHEREAL_COLOR);
            this.lid.render(poseStack, buffer, light, packedOverlay, ETHEREAL_COLOR);
        } else {
            this.shell.render(poseStack, buffer, packedLight, packedOverlay, color);
            this.iris.render(poseStack, buffer, packedLight, packedOverlay, this.eyeColor);
            this.lid.render(poseStack, buffer, packedLight, packedOverlay, color);
        }

        poseStack.popPose();
    }
}
