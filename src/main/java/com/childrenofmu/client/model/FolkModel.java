package com.childrenofmu.client.model;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

import com.childrenofmu.ChildrenOfMu;
import com.childrenofmu.entity.folk.FolkEntity;
import com.childrenofmu.entity.folk.FolkRace;
import com.mojang.blaze3d.vertex.PoseStack;
import com.mojang.blaze3d.vertex.VertexConsumer;
import net.minecraft.client.model.ArmedModel;
import net.minecraft.client.model.EntityModel;
import net.minecraft.client.model.HeadedModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.util.Mth;
import net.minecraft.world.entity.HumanoidArm;

/**
 * The shared body for the walking folk: head, body, two arms, two legs, and (for some races) a tail. Some parts
 * belong to one variant only (a cape, a beret) and are hidden on the others.
 * The geometry of each race comes from FolkShapes (generated by tools/make_folk_assets.py).
 */
public class FolkModel extends EntityModel<FolkEntity> implements ArmedModel, HeadedModel {
    private final FolkRace race;
    private final ModelPart root;
    private final ModelPart head, body, rightArm, leftArm, rightLeg, leftLeg;
    private final List<ModelPart> tails = new ArrayList<>();
    private final List<Float> tailRestX = new ArrayList<>();
    private float beatTicks = 12.0F;
    /** Parts only some variants have, with those variants. */
    private final Map<ModelPart, List<String>> variantParts = new HashMap<>();

    public FolkModel(ModelPart root, FolkRace race) {
        this.race = race;
        this.root = root;
        this.head = root.getChild("head");
        this.body = root.getChild("body");
        this.rightArm = root.getChild("right_arm");
        this.leftArm = root.getChild("left_arm");
        this.rightLeg = root.getChild("right_leg");
        this.leftLeg = root.getChild("left_leg");
        Map<String, ModelPart> byName = new HashMap<>();
        List<FolkShapes.Part> pending = new ArrayList<>();
        for (FolkShapes.Part p : FolkShapes.PARTS) {
            if (p.race().equals(race.id())) {
                pending.add(p);
            }
        }
        boolean progress = true;
        while (!pending.isEmpty() && progress) {          // parents first, whatever order the parts are listed in
            progress = false;
            for (java.util.Iterator<FolkShapes.Part> it = pending.iterator(); it.hasNext(); ) {
                FolkShapes.Part p = it.next();
                ModelPart parent = p.parent() == null ? root : byName.get(p.parent());
                if (parent == null) {
                    continue;
                }
                it.remove();
                progress = true;
                if (!parent.hasChild(p.name())) {
                    continue;
                }
                ModelPart mp = parent.getChild(p.name());
                byName.put(p.name(), mp);
                if (p.variants().length > 0) {
                    this.variantParts.put(mp, Arrays.asList(p.variants()));
                }
                if (p.parent() == null && p.name().startsWith("tail")) {
                    this.tails.add(mp);
                    this.tailRestX.add(mp.xRot);
                }
            }
        }
    }

    public static ModelLayerLocation layer(FolkRace race) {
        return new ModelLayerLocation(ChildrenOfMu.id("folk_" + race.id()), "main");
    }

    public static LayerDefinition createLayer(FolkRace race) {
        MeshDefinition mesh = new MeshDefinition();
        Map<String, PartDefinition> defs = new HashMap<>();
        // Parts can be listed in any order: keep passing over the list, adding each part once its parent exists.
        java.util.List<FolkShapes.Part> pending = new java.util.ArrayList<>();
        for (FolkShapes.Part p : FolkShapes.PARTS) {
            if (p.race().equals(race.id())) {
                pending.add(p);
            }
        }
        while (!pending.isEmpty()) {
            boolean progress = false;
            for (java.util.Iterator<FolkShapes.Part> it = pending.iterator(); it.hasNext(); ) {
                FolkShapes.Part p = it.next();
                if (p.parent() != null && !defs.containsKey(p.parent())) {
                    continue;
                }
                it.remove();
                progress = true;
            CubeListBuilder cubes = CubeListBuilder.create();
            for (FolkShapes.Box b : p.boxes()) {
                cubes.texOffs(b.u(), b.v()).addBox(b.x(), b.y(), b.z(), b.w(), b.h(), b.d());
            }
            PartDefinition parent = p.parent() == null ? mesh.getRoot() : defs.get(p.parent());
            defs.put(p.name(), parent.addOrReplaceChild(p.name(), cubes, PartPose.offsetAndRotation(
                    p.pivotX(), p.pivotY(), p.pivotZ(),
                    p.rotX() * Mth.DEG_TO_RAD, p.rotY() * Mth.DEG_TO_RAD, p.rotZ() * Mth.DEG_TO_RAD)));
            }
            if (!progress) {
                ChildrenOfMu.LOGGER.warn("Folk model {}: parts with missing parents skipped: {}", race.id(),
                        pending.stream().map(FolkShapes.Part::name).toList());
                break;
            }
        }
        return LayerDefinition.create(mesh, FolkShapes.TEX_WIDTH, FolkShapes.texHeight(race.id()));
    }

    @Override
    public void setupAnim(FolkEntity entity, float limbSwing, float limbSwingAmount, float ageInTicks,
                          float netHeadYaw, float headPitch) {
        for (ModelPart part : new ModelPart[]{this.head, this.body, this.rightArm, this.leftArm, this.rightLeg, this.leftLeg}) {
            part.y = part.getInitialPose().y;
            part.yRot = 0.0F;
            part.zRot = 0.0F;
        }
        String variant = entity.getVariantName();
        this.variantParts.forEach((part, variants) -> part.visible = variants.contains(variant));
        if (entity.isResting()) {
            if (this.race == FolkRace.BAT) {
                poseForHanging(ageInTicks);
            } else if (this.race == FolkRace.CAT) {
                poseForSitting(ageInTicks, netHeadYaw, headPitch);
            } else {
                poseForRest(ageInTicks);
            }
            return;
        }
        this.head.yRot = netHeadYaw * Mth.DEG_TO_RAD;
        this.head.xRot = headPitch * Mth.DEG_TO_RAD;
        this.head.zRot = 0.0F;
        // Little legs take quick steps (shorter ones under a robe).
        float swing = limbSwing * 0.9F;
        float stride = this.race.robed() ? 0.5F : 1.3F;
        this.rightLeg.xRot = Mth.cos(swing) * stride * limbSwingAmount;
        this.leftLeg.xRot = Mth.cos(swing + Mth.PI) * stride * limbSwingAmount;
        this.rightArm.xRot = Mth.cos(swing + Mth.PI) * 0.9F * limbSwingAmount;
        this.leftArm.xRot = Mth.cos(swing) * 0.9F * limbSwingAmount;
        if (!entity.getMainHandItem().isEmpty()) {
            this.rightArm.xRot = this.rightArm.xRot * 0.5F - 0.3F;   // holding a tool out a little
        }
        // A gentle bob of the arms when standing.
        this.rightArm.zRot = Mth.cos(ageInTicks * 0.09F) * 0.05F + 0.05F;
        this.leftArm.zRot = -(Mth.cos(ageInTicks * 0.09F) * 0.05F + 0.05F);
        if (entity.isPlaying()) {
            this.beatTicks = com.childrenofmu.entity.folk.FolkJazz.style(entity.level().getGameTime()).beat;
            poseForMusic(variant, ageInTicks);
        }
        if ("beautiful".equals(variant) && limbSwingAmount < 0.1F) {
            poseForGrooming(ageInTicks + entity.getId() * 37);
        }
        if (entity.isAggressive() && !entity.getMainHandItem().isEmpty()) {
            // Raising a blowpipe (or whatever it carries) to aim.
            this.rightArm.xRot = -1.45F + this.head.xRot;
            this.rightArm.yRot = this.head.yRot - 0.2F;
            this.rightArm.zRot = 0.0F;
        }
        for (int i = 0; i < this.tails.size(); i++) {
            ModelPart tail = this.tails.get(i);
            tail.yRot = Mth.sin(ageInTicks * 0.12F) * 0.25F;
            tail.xRot = this.tailRestX.get(i) + Mth.cos(swing) * 0.15F * limbSwingAmount;
        }
    }

    /** The Beautiful Ones groom themselves all day: licking their paws, washing their face, smoothing their ears. */
    private void poseForGrooming(float age) {
        int phase = (int) (age / 90.0F) % 3;
        float t = age * 0.35F;
        switch (phase) {
            case 0 -> {   // licking the paws
                this.head.xRot = 0.35F;
                this.rightArm.xRot = -1.7F + Mth.sin(t) * 0.12F;
                this.leftArm.xRot = -1.7F - Mth.sin(t) * 0.12F;
                this.rightArm.zRot = 0.45F;
                this.leftArm.zRot = -0.45F;
            }
            case 1 -> {   // washing the face, one paw then the other
                this.rightArm.xRot = -1.9F + Mth.sin(t) * 0.35F;
                this.leftArm.xRot = -1.9F - Mth.sin(t) * 0.35F;
                this.rightArm.zRot = 0.5F;
                this.leftArm.zRot = -0.5F;
                this.head.zRot = Mth.sin(t * 0.5F) * 0.12F;
            }
            default -> {   // smoothing the ears back
                this.rightArm.xRot = -2.7F + Mth.sin(t) * 0.15F;
                this.leftArm.xRot = -2.7F + Mth.sin(t) * 0.15F;
                this.rightArm.zRot = 0.3F;
                this.leftArm.zRot = -0.3F;
                this.head.xRot = -0.15F;
            }
        }
    }

    /** Bat folk at their jazz: nodding to the beat, with each player's own pose. */
    /**
     * Torpid for the night: down on the mat, head tucked low, arms folded in, legs folded flat underneath, like a
     * resting frog. A slow breath lifts the body a little.
     */
    private void poseForRest(float ageInTicks) {
        float drop = 6.0F;
        float breath = Mth.sin(ageInTicks * 0.05F) * 0.25F;
        this.head.y += drop + 1.0F - breath;
        this.head.xRot = 0.35F;
        this.head.zRot = 0.0F;
        this.body.y += drop - breath;
        this.rightArm.y += drop + 1.0F;
        this.leftArm.y += drop + 1.0F;
        this.rightArm.xRot = -0.25F;
        this.leftArm.xRot = -0.25F;
        this.rightArm.zRot = -0.35F;
        this.leftArm.zRot = 0.35F;
        this.rightLeg.y += drop;
        this.leftLeg.y += drop;
        this.rightLeg.xRot = -1.45F;
        this.leftLeg.xRot = -1.45F;
        this.rightLeg.zRot = 0.15F;
        this.leftLeg.zRot = -0.15F;
    }

    /** Sitting on a cushion (the Great Gar): legs out in front, paws on the belly, head turning to watch the room. */
    private void poseForSitting(float ageInTicks, float netHeadYaw, float headPitch) {
        float drop = 6.0F;
        float breath = Mth.sin(ageInTicks * 0.06F) * 0.2F;
        this.head.y += drop - breath;
        this.head.yRot = netHeadYaw * Mth.DEG_TO_RAD;
        this.head.xRot = headPitch * Mth.DEG_TO_RAD;
        this.body.y += drop - breath;
        this.rightArm.y += drop;
        this.leftArm.y += drop;
        this.rightArm.xRot = -0.45F;
        this.leftArm.xRot = -0.45F;
        this.rightArm.zRot = 0.25F;
        this.leftArm.zRot = -0.25F;
        this.rightLeg.y += drop;
        this.leftLeg.y += drop;
        this.rightLeg.xRot = -1.5F;
        this.leftLeg.xRot = -1.5F;
        this.rightLeg.yRot = 0.2F;
        this.leftLeg.yRot = -0.2F;
    }

    /**
     * A bat asleep in its roost (the renderer turns it upside down): legs straight up to the post, wings wrapped
     * round the body, head tucked, swaying a little.
     */
    private void poseForHanging(float ageInTicks) {
        float sway = Mth.sin(ageInTicks * 0.04F) * 0.04F;
        this.head.xRot = 0.45F;
        this.head.zRot = sway;
        this.rightArm.xRot = -0.55F;
        this.leftArm.xRot = -0.55F;
        this.rightArm.zRot = -0.75F;
        this.leftArm.zRot = 0.75F;
        this.rightArm.yRot = 0.3F;
        this.leftArm.yRot = -0.3F;
        this.rightLeg.xRot = 0.0F;
        this.leftLeg.xRot = 0.0F;
        this.rightLeg.zRot = 0.05F;
        this.leftLeg.zRot = -0.05F;
        this.body.zRot = sway;
    }

    private void poseForMusic(String variant, float age) {
        float beat = age * Mth.TWO_PI / this.beatTicks;   // in time with FolkJazz's current style
        this.head.xRot += Mth.sin(beat) * 0.12F;
        switch (variant) {
            case "jazz" -> {   // both hands up at the saxophone's keys
                this.rightArm.xRot = -1.1F + Mth.sin(beat * 2) * 0.05F;
                this.leftArm.xRot = -1.25F;
                this.rightArm.zRot = 0.35F;
                this.leftArm.zRot = -0.35F;
            }
            case "folk" -> {   // plucking the bass
                this.leftArm.xRot = -0.9F;
                this.leftArm.zRot = -0.2F;
                this.rightArm.xRot = -0.5F + Mth.sin(beat) * 0.35F;
            }
            case "flapper" -> {   // dancing the Charleston, arms swinging high
                this.rightArm.zRot = 2.2F + Mth.sin(beat) * 0.5F;
                this.leftArm.zRot = -2.2F - Mth.sin(beat) * 0.5F;
                this.rightLeg.xRot = Mth.sin(beat) * 0.6F;
                this.leftLeg.xRot = -Mth.sin(beat) * 0.6F;
            }
            default -> {
            }
        }
    }

    @Override
    public void renderToBuffer(PoseStack poseStack, VertexConsumer buffer, int packedLight, int packedOverlay, int color) {
        this.root.render(poseStack, buffer, packedLight, packedOverlay, color);
    }

    @Override
    public void translateToHand(HumanoidArm side, PoseStack poseStack) {
        (side == HumanoidArm.LEFT ? this.leftArm : this.rightArm).translateAndRotate(poseStack);
        // The held-item layer expects a full-size arm (hand 10 units down); move it up to this arm's hand.
        poseStack.translate(0.0F, (this.race.handY() - 10.0F) / 16.0F, 0.0F);
    }

    @Override
    public ModelPart getHead() {
        return this.head;
    }
}
